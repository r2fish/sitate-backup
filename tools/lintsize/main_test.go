package main

import (
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"testing"
)

func gen(n int, header string) string {
	var b strings.Builder
	b.WriteString(header + "package x\n\nvar (\n")
	for i := 0; i < n; i++ {
		b.WriteString("\t_ = 0\n")
	}
	b.WriteString(")\n")
	return b.String()
}

func write(t *testing.T, dir, name, content string) {
	t.Helper()
	p := filepath.Join(dir, name)
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(p, []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
}

// 作業ディレクトリに HEAD の無い git の木を作り、run を走らせる。
func setup(t *testing.T) string {
	dir := t.TempDir()
	cmd := exec.Command("git", "init", "-q")
	cmd.Dir = dir
	if out, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("git init: %v %s", err, out)
	}
	old, _ := os.Getwd()
	if err := os.Chdir(dir); err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = os.Chdir(old) })
	t.Setenv("LINT_BASE", "")
	return dir
}

func runLint(t *testing.T) int {
	t.Helper()
	null, _ := os.OpenFile(os.DevNull, os.O_WRONLY, 0)
	defer null.Close()
	return run(null, null)
}

func TestLintSize(t *testing.T) {
	dir := setup(t)
	write(t, dir, "ok.go", gen(10, ""))
	if rc := runLint(t); rc != 0 {
		t.Fatalf("小さいファイルは合格: rc=%d", rc)
	}
	write(t, dir, "big.go", gen(450, ""))
	if rc := runLint(t); rc != 1 {
		t.Fatalf("400 行を超えるファイルは不合格のはず: rc=%d", rc)
	}
	// ファイル内の印では外れない
	write(t, dir, "big.go", gen(450, "//nolint\n// lint-size:ignore\n"))
	if rc := runLint(t); rc != 1 {
		t.Fatalf("ファイル内の印では外れないはず: rc=%d", rc)
	}
	// 生成コードは対象外
	write(t, dir, "big.go", gen(450, "// Code generated by x; DO NOT EDIT.\n\n"))
	if rc := runLint(t); rc != 0 {
		t.Fatalf("生成コードは対象外のはず: rc=%d", rc)
	}
	// 許可リストのパスは対象外
	write(t, dir, "big.go", gen(450, ""))
	write(t, dir, "tools/lintsize/allowlist.txt", "big.go\t理由\n")
	if rc := runLint(t); rc != 0 {
		t.Fatalf("許可リストのパスは対象外のはず: rc=%d", rc)
	}
	// テストのファイルは 600 まで
	write(t, dir, "tools/lintsize/allowlist.txt", "")
	os.Remove(filepath.Join(dir, "big.go"))
	write(t, dir, "a_test.go", gen(500, ""))
	if rc := runLint(t); rc != 0 {
		t.Fatalf("テストのファイルは 600 行まで: rc=%d", rc)
	}
	write(t, dir, "a_test.go", gen(650, ""))
	if rc := runLint(t); rc != 1 {
		t.Fatalf("テストのファイルも 600 行を超えたら不合格: rc=%d", rc)
	}
}

func TestLintSizeFunctionLength(t *testing.T) {
	dir := setup(t)
	body := "package x\n\nfunc f() {\n" + strings.Repeat("\t_ = 1\n", 70) + "}\n"
	write(t, dir, "f.go", body)
	if rc := runLint(t); rc != 1 {
		t.Fatalf("60 行を超える関数は不合格: rc=%d", rc)
	}
}
